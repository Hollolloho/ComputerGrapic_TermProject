"""Validate artist boss/room data and bake shared rig + local collision triangles."""
import argparse
import hashlib
import json
import math
from pathlib import Path


def generate(root):
    base = root / 'asset/boss_e/runtime'
    raw = (base / 'assembly.json').read_bytes()
    boss = json.loads(raw)
    room = json.loads((root / 'asset/core_room/runtime/placement.json').read_bytes())
    props = json.loads((root / 'asset/props/runtime/assembly.json').read_bytes())
    assert boss['units'] == room['units'] == 'metres'
    assert boss['up'] == room['up'] == '+Y' and boss['front'] == '+Z'
    assert boss['normal_space'] == 'tangent_opengl_positive_y'
    nodes = list(boss['nodes'])
    parts = boss['parts']
    def vec(v):
        assert len(v)==3 and all(math.isfinite(x) for x in v)
        return '{'+','.join(f'{float(x):.8f}f' for x in v)+'}'
    lines = ['#pragma once','#include "combat.h"','#include <array>',
        'namespace aegis::boss_asset {',
        '// Generated by tools/generate_boss_layout.py; do not hand edit.',
        f'// Assembly SHA256: {hashlib.sha256(raw).hexdigest()}',
        f'inline constexpr int nodeCount={len(nodes)},partCount={len(parts)};',
        'struct Node { glm::vec3 translation,rotation; int parent; };',
        f'inline const std::array<Node,{len(nodes)}> nodes{{{{']
    for name in nodes:
        node=boss['nodes'][name]
        parent=nodes.index(node['parent']) if node['parent'] else -1
        assert parent<nodes.index(name)
        lines.append(f'    {{{vec(node["translation_m"])},{vec(node["rest_rotation_deg"])},{parent}}},')
    lines+=['}};','struct Part { const char* mesh; int node,triangles,start; glm::vec3 low,high; };',
            f'inline const std::array<Part,{len(parts)}> parts{{{{']
    triangles=[]
    for part in parts:
        path=(base/part['obj']).resolve()
        assert path.is_relative_to(base.resolve())
        points=[]; faces=[]
        for line in path.read_text().splitlines():
            fields=line.split()
            if not fields: continue
            if fields[0]=='v': points.append([float(x) for x in fields[1:4]])
            elif fields[0]=='f':
                face=[int(x.split('/')[0]) for x in fields[1:]]
                face=[i-1 if i>0 else len(points)+i for i in face]
                for j in range(1,len(face)-1): faces.append([points[i] for i in [face[0],face[j],face[j+1]]])
        assert len(faces)==part['triangles']
        low=[min(v[i] for v in points) for i in range(3)]
        high=[max(v[i] for v in points) for i in range(3)]
        lines.append(f'    {{"{part["obj"]}",{nodes.index(part["parent"])},{len(faces)},{len(triangles)},{vec(low)},{vec(high)}}},')
        triangles+=faces
    lines+=['}};']
    for name in ['lower_armor_L_slide','lower_armor_R_slide','turret_L_yaw','turret_L_pitch','turret_R_yaw','turret_R_pitch','muzzle_L','muzzle_R','core_visual']:
        lines.append(f'inline constexpr int {name}={nodes.index(name)};')
    for name in ['core_crystal','sector_warning','turret_warning_L','turret_warning_R']:
        lines.append(f'inline constexpr int part_{name}={next(i for i,p in enumerate(parts) if p["id"]==name)};')
    opening=boss['nodes']['lower_armor_L_slide']['motion']['keys'][-1]['translation_from_rest_m'][0]
    lines.append(f'inline constexpr float armorTravel={abs(opening):.8f}f;')
    weak=next(p for p in boss['collision_proxies_game_axes'] if p['id']=='weakspot')
    assert weak['parent']=='core_visual'
    lines += [f'inline const glm::vec3 weakCenter{vec(weak["center_local_m"])};',
              f'inline const glm::vec3 weakHalf{vec(weak["half_extents_m"])};']
    placements={p['id']:p for p in room['placements']}
    lines.append(f'inline const glm::vec3 mount{vec(placements["boss_e"]["translation_m"])};')
    supply=placements['weapon_supply']['translation_m']
    lines.append(f'inline const glm::vec3 supplyPosition{vec(supply)};')
    anchor=props['assets']['cw01c_supply_station']['interaction_point_m']
    lines.append(f'inline const glm::vec3 supplyInteraction{vec([a+b for a,b in zip(supply,anchor)])};')
    anchor=props['assets']['cw01c_supply_station']['weapon_anchor']['root_translation_m']
    lines.append(f'inline const glm::vec3 supplyWeapon{vec([a+b for a,b in zip(supply,anchor)])};')
    lines.append(f'inline const std::array<combat::Collider,{len(room["static_colliders"])}> walls{{{{')
    for i,box in enumerate(room['static_colliders']):
        lines.append(f'    {{{22000+i},combat::HitKind::Wall,{vec(box["min"])},{vec(box["max"])}}},')
    lines+=['}};','struct Cover { glm::vec3 translation,scale; float yaw; };','inline const std::array<Cover,2> covers{{']
    for key in ['cover_left','cover_right']:
        p=placements[key]
        lines.append(f'    {{{vec(p["translation_m"])},{vec(p["scale"])},{p["yaw_deg"]:.8f}f}},')
    lines+=['}};','struct Texture { const char* name; const char* file; bool srgb; };','inline const std::array<Texture,5> textures{{']
    for name in ['basecolor','normal','metallic','roughness','emission']:
        srgb=name in ['basecolor','emission']
        path=base/boss['maps'][name]
        assert path.read_bytes()[:8]==b'\x89PNG\r\n\x1a\n'
        lines.append(f'    {{"{name}","{boss["maps"][name]}",{str(srgb).lower()}}},')
    lines+=['}};',f'inline constexpr float emission={boss["emission_multiplier"]:.8f}f;','} // namespace aegis::boss_asset','']
    collision=['// Generated local-space collision triangles.']
    collision+=[f'    {{{vec(t[0])},{vec(t[1])},{vec(t[2])}}},' for t in triangles]
    return '\n'.join(lines),'\n'.join(collision)+'\n'


if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    p.add_argument('--check',action='store_true')
    args=p.parse_args()
    output=generate(args.root)
    for name,content in zip(['boss_layout.generated.h','boss_triangles.generated.inc'],output):
        target=args.root/'game/src'/name
        if args.check: assert target.read_text(encoding='utf-8')==content, f'Regenerate {name}'
        else: target.write_text(content,encoding='utf-8')
    print('Boss 14-part rig, textures, triangle counts, weakspot and core-room layout: PASS')
