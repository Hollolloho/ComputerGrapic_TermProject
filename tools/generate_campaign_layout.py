"""Generate entry-room presentation anchors from the shared artist layout."""
import argparse
import hashlib
import json
from pathlib import Path


def generate(root):
    file=root/'asset/entry_room/runtime/placement.json'
    raw=file.read_bytes(); data=json.loads(raw)
    assert data['units']=='metres' and data['up']=='+Y' and data['forward']=='-Z'
    path=root/'asset/entry_room/runtime'/data['geometry']['file']
    count=sum(len(line.split())-3 for line in path.read_text().splitlines() if line.startswith('f '))
    assert count==data['geometry']['triangles']
    def vec(v): return '{'+','.join(f'{float(x):.8f}f' for x in v)+'}'
    player=data['anchors']['player_start']; terminal=data['anchors']['analysis_terminal']
    return '\n'.join(['#pragma once','#include <glm/vec3.hpp>','namespace aegis::campaign_asset {',
        '// Generated by tools/generate_campaign_layout.py.',f'// SHA256: {hashlib.sha256(raw).hexdigest()}',
        f'inline constexpr const char* entryMesh="asset/entry_room/runtime/{data["geometry"]["file"]}";',
        f'inline const glm::vec3 playerStart{vec(player["position"])};',
        f'inline constexpr float playerYaw={float(player["yaw_degrees"]):.8f}f,playerPitch={float(player["pitch_degrees"]):.8f}f;',
        f'inline const glm::vec3 terminalPosition{vec(terminal["position"])};',
        f'inline constexpr float terminalYaw={float(terminal["yaw_degrees"]):.8f}f;',
        '} // namespace aegis::campaign_asset',''])


if __name__=='__main__':
    p=argparse.ArgumentParser(); p.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1]); p.add_argument('--check',action='store_true')
    args=p.parse_args(); content=generate(args.root); out=args.root/'game/src/campaign_layout.generated.h'
    if args.check: assert out.read_text(encoding='utf-8')==content,'Regenerate campaign layout'
    else: out.write_text(content,encoding='utf-8')
    print('Entry room 3812 triangles and campaign presentation anchors: PASS')
