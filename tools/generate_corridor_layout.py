"""Generate shared drawing/collision data from the closed-door scene manifest."""
import argparse
import hashlib
import json
from pathlib import Path


def generate(root):
    source = root / 'asset/corridor/test_scene/scene_manifest.json'
    raw = source.read_bytes()
    data = json.loads(raw)
    assert data['units'] == 'metres' and data['up'] == '+Y'
    placements = data['placements']
    names = [p['asset'] for p in placements]
    assert names == ['corridor', 'door_frame', 'door_left', 'door_right', 'cover']
    def vec(v):
        assert len(v) == 3
        return '{' + ','.join(f'{float(n):.8f}f' for n in v) + '}'
    lines = ['#pragma once', '#include "combat.h"', '#include <array>',
             'namespace aegis::corridor_asset {',
             '// Generated by tools/generate_corridor_layout.py; do not hand edit.',
             f'// Manifest SHA256: {hashlib.sha256(raw).hexdigest()}',
             'struct Placement { const char* file; glm::vec3 translation; float yawDegrees; int parent; };',
             'inline const std::array<Placement,5> placements{{']
    for p in placements:
        parent = names.index(p['parent']) if p['parent'] else -1
        filename = data['assets'][p['asset']]['file']
        lines.append(f'    {{"{filename}",{vec(p["translation"])},{float(p.get("yaw_degrees",0)):.8f}f,{parent}}},')
    lines += ['}};']
    walls = [(p['min'], p['max']) for p in data['static_colliders']]
    for door in data['dynamic_colliders']:
        bounds = data['assets'][door['asset_bounds']]['bounds']
        parent = placements[names.index(door['parent'])]['translation']
        offset = [a+b for a,b in zip(parent,door['translation_closed'])]
        low = [a+b for a,b in zip(bounds['min'],offset)]
        high = [a+b for a,b in zip(bounds['max'],offset)]
        # Closed leaves have a 4 cm visual seam; seal it for point projectiles.
        if door['id'] == 'door_left':
            high[0] = parent[0]
        elif door['id'] == 'door_right':
            low[0] = parent[0]
        walls.append((low,high))
    lines.append(f'inline const std::array<combat::Collider,{len(walls)}> walls{{{{')
    for i,(low,high) in enumerate(walls):
        assert all(a<=b for a,b in zip(low,high))
        lines.append(f'    {{{10000+i},combat::HitKind::Wall,{vec(low)},{vec(high)}}},')
    lines += ['}};', '} // namespace aegis::corridor_asset', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate(args.root)
    output = args.root / 'game/src/corridor_layout.generated.h'
    if args.check:
        assert output.read_text(encoding='utf-8') == content, 'Regenerate corridor layout'
    else:
        output.write_text(content, encoding='utf-8')
    print('Corridor manifest drawing placements and 12 collision proxies: PASS')
