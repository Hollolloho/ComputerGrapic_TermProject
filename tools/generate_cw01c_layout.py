"""Generate the weapon's C++ assembly table from the artist-owned manifest.

No JSON library is needed in the running game. Run again after an asset update.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct


def generate(root: Path) -> str:
    runtime = root / "asset/cw01c/runtime"
    source = (runtime / "assembly.json").read_bytes()
    data = json.loads(source)
    for key, expected in {"version": 1, "units": "metres", "up": "+Y", "front": "+Z",
                          "normal_space": "tangent_opengl_positive_y",
                          "basecolor_color_space": "sRGB", "data_color_space": "linear"}.items():
        if data.get(key) != expected:
            raise ValueError(f"Unsupported {key}: {data.get(key)!r}")
    parts = data["parts"]
    if len(parts) != 8 or len({part["id"] for part in parts}) != 8:
        raise ValueError("CW-01 C requires eight distinct parts")

    def asset_path(value):
        path = (runtime / value).resolve()
        if not path.is_relative_to(runtime.resolve()) or not path.is_file():
            raise ValueError(f"Missing/out-of-directory asset: {value}")
        return path

    rows = []
    total = 0
    for part in parts:
        offset = part["assembled_translation"]
        if len(offset) != 3 or not all(math.isfinite(value) for value in offset):
            raise ValueError(f"Invalid translation: {part['id']}")
        faces = [line for line in asset_path(part["mesh"]).read_text().splitlines() if line.startswith("f ")]
        if len(faces) != part["triangles"] or any(len(face.split()) != 4 for face in faces):
            raise ValueError(f"Triangle count mismatch: {part['id']}")
        total += len(faces)
        xyz = ", ".join(f"{float(value):.9f}f" for value in offset)
        rows.append(f'    {{{json.dumps(part["id"])}, {json.dumps(part["mesh"])}, {{{xyz}}}, {len(faces)}}}')
    textures = []
    for name in ("basecolor", "normal", "metallic", "roughness", "emission"):
        value = data["maps"][name]
        png = asset_path(value).read_bytes()
        if png[:8] != b"\x89PNG\r\n\x1a\n" or struct.unpack(">II", png[16:24]) != (data["atlas_size"],) * 2:
            raise ValueError(f"Invalid texture dimensions: {name}")
        textures.append(f'    {{{json.dumps(name)}, {json.dumps(value)}, {str(name == "basecolor").lower()}}}')
    emission = float(data["emission_multiplier"])
    if not math.isfinite(emission) or emission < 0:
        raise ValueError("Invalid emission multiplier")
    return ("// Generated by tools/generate_cw01c_layout.py; do not edit by hand.\n"
            f"// Manifest SHA256: {hashlib.sha256(source).hexdigest()}\n"
            "#pragma once\n#include <array>\n#include <glm/vec3.hpp>\n\n"
            "namespace aegis::weapon_asset {\n"
            "struct Part { const char* id; const char* mesh; glm::vec3 offset; int triangles; };\n"
            "struct Texture { const char* name; const char* file; bool srgb; };\n"
            "inline const std::array<Part, 8> parts{{\n" + ",\n".join(rows) + "\n}};\n"
            "inline constexpr std::array<Texture, 5> textures{{\n" + ",\n".join(textures) + "\n}};\n"
            f"inline constexpr int totalTriangles = {total};\n"
            f"inline constexpr float emissionMultiplier = {emission:.9f}f;\n"
            "} // namespace aegis::weapon_asset\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(args.root)
    output = args.root / "game/src/cw01c_layout.generated.h"
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != result:
            raise SystemExit("Weapon layout is stale; run tools/generate_cw01c_layout.py")
        print("CW-01 C manifest, 8 OBJ triangle counts, 5 PNG dimensions and generated layout: PASS")
    else:
        output.write_text(result, encoding="utf-8", newline="\n")
        print(f"Generated: {output}")
