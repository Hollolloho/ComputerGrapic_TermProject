"""Validate artist terminal metadata and generate one shared scene layout."""
import argparse
import hashlib
import json
import math
from pathlib import Path


def generate(root):
    source = root / 'asset/props/runtime/assembly.json'
    raw = source.read_bytes()
    data = json.loads(raw)
    assert data['units'] == 'metres' and data['up'] == '+Y' and data['front'] == '+Z'
    asset = data['assets']['analysis_terminal']
    mesh = source.parent / asset['mesh']
    assert mesh.resolve().is_relative_to(source.parent.resolve())
    triangles = sum(len(line.split())-3 for line in mesh.read_text().splitlines() if line.startswith('f '))
    assert triangles == asset['triangles']
    position = [0.95, 0, -1.5]  # Reachable to the right of the fixed test camera.
    bounds = asset['bounds_xyz_m']
    def vec(value):
        assert len(value) == 3 and all(math.isfinite(n) for n in value)
        return '{'+','.join(f'{float(n):.8f}f' for n in value)+'}'
    low = [b[0]+p for b,p in zip(bounds,position)]
    high = [b[1]+p for b,p in zip(bounds,position)]
    assert all(a<=b for a,b in zip(low,high))
    point = [a+b for a,b in zip(position,asset['interaction_point_m'])]
    return '\n'.join(['#pragma once','#include "combat.h"','namespace aegis::terminal_asset {',
        '// Generated by tools/generate_terminal_layout.py; do not hand edit.',
        f'// Manifest SHA256: {hashlib.sha256(raw).hexdigest()}',
        f'inline constexpr const char* mesh="asset/props/runtime/{asset["mesh"]}";',
        f'inline constexpr int triangles={triangles};',
        f'inline const glm::vec3 position{vec(position)};',
        f'inline const glm::vec3 interactionPoint{vec(point)};',
        f'inline const combat::Collider collider{{12000,combat::HitKind::Wall,{vec(low)},{vec(high)}}};',
        '} // namespace aegis::terminal_asset',''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    content = generate(args.root)
    output = args.root / 'game/src/terminal_layout.generated.h'
    if args.check:
        assert output.read_text(encoding='utf-8') == content, 'Regenerate terminal layout'
    else:
        output.write_text(content,encoding='utf-8')
    print('Terminal metadata, 3564 triangles and generated interaction/collision layout: PASS')
