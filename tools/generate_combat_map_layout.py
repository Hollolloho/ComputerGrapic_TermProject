"""Generate first-corridor collision from the friend's OBJ and placement data."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
ASSET=ROOT/'asset/combat_map'

def generate():
    source=(ASSET/'placement.json').read_bytes()
    data=json.loads(source)
    assert data['units']=='metres' and data['up']=='+Y' and data['forward_travel']=='-Z'
    mesh=(ASSET/data['mesh']).read_bytes()
    vertices=[]; objects={}; name=None; triangles=0
    for line in mesh.decode().splitlines():
        if line.startswith('v '): vertices.append(tuple(map(float,line.split()[1:4])))
        elif line.startswith('o '): name=line[2:]; objects[name]=set()
        elif line.startswith('f '):
            indices=[int(v.split('/')[0])-1 for v in line.split()[1:]]
            assert len(indices)>=3 and name is not None
            objects[name].update(indices); triangles+=len(indices)-2
    def bounds(names):
        points=[vertices[i] for n in names for i in objects[n]]
        return ([min(p[a] for p in points) for a in range(3)], [max(p[a] for p in points) for a in range(3)])
    walls=[]
    for name in objects:
        if name.startswith('01_') or name.startswith('02_Interlock_gate_'):
            walls.append((name,*bounds([name])))
    for cover in data['cover_footprints']:
        key=cover['id']
        if key not in ('A01','A02'): continue
        names=[n for n in objects if n=='Cover_'+key or n.startswith(key+'_')]
        low,high=bounds(names)
        for a,extent in ((0,cover['width']),(2,cover['depth'])):
            assert low[a]<=cover['center'][a]-extent/2+0.001 and high[a]>=cover['center'][a]+extent/2-0.001
        walls.append(('Cover_'+key,low,high))
    assert len(walls)>50
    drone=data['encounters']['corridor_a'][0]; assert drone['type']=='drone'
    def f(x): return format(x,'.6f')+'f'
    def v(p): return '{'+','.join(f(x) for x in p)+'}'
    out=['// Generated by tools/generate_combat_map_layout.py; do not hand edit.',
        '#pragma once','#include "combat.h"','#include <array>',
        'namespace aegis::combat_map_asset {',
        'inline constexpr const char* mesh="asset/combat_map/'+data['mesh']+'";',
        'inline constexpr const char* sourceHash="'+hashlib.sha256(source+mesh).hexdigest()+'";',
        'inline constexpr int triangles='+str(triangles)+';',
        'inline const glm::vec3 playerStart='+v(data['player_start'])+';',
        'inline const glm::vec3 droneSpawn='+v(drone['position'])+';',
        'inline constexpr float droneYawDegrees='+f(drone['yaw_degrees'])+';',
        'inline const glm::vec3 supply=playerStart+glm::vec3(-0.8f,1.15f,-1.4f);',
        'inline const glm::vec3 terminal=playerStart+glm::vec3(0.95f,0,-1.5f);',
        'inline const std::array<combat::Collider,'+str(len(walls))+'> walls={{']
    for i,(name,low,high) in enumerate(walls):
        out.append('    {'+str(30000+i)+',combat::HitKind::Wall,'+v(low)+','+v(high)+'}, // '+name)
    out+=['}};','}']
    return '\n'.join(out)+'\n'
if __name__=='__main__':
    args=argparse.ArgumentParser(); args.add_argument('--check',action='store_true'); opt=args.parse_args()
    target=ROOT/'game/src/combat_map_layout.generated.h'; output=generate()
    if opt.check:
        assert target.read_text(encoding='utf-8')==output,'Regenerate combat map layout'
        print('Combat map layout: PASS')
    else:
        target.write_text(output,encoding='utf-8'); print('Generated',target)
